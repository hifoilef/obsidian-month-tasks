import esbuild from 'esbuild';
import { existsSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import process from 'process';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
*/`;

const prod = process.argv[2] === 'production';
const projectRoot = import.meta.dirname;
const localExtensions = ['', '.ts', '.tsx', '.js', '.mjs', '.json'];

/** Resolves project-local modules without scanning unrelated parent folders. */
function resolveLocalImport(resolveDir, importPath) {
  const basePath = path.resolve(resolveDir, importPath);
  const candidates = [
    ...localExtensions.map((extension) => `${basePath}${extension}`),
    ...localExtensions.slice(1).map((extension) => path.join(basePath, `index${extension}`)),
  ];
  return candidates.find((candidate) => (
    existsSync(candidate) && statSync(candidate).isFile()
  ));
}

const localModulesPlugin = {
  name: 'month-tasks-local-modules',
  setup(build) {
    build.onResolve({ filter: /^month-tasks-entry$/ }, () => ({
      path: path.join(projectRoot, 'src', 'main.ts'),
      namespace: 'month-tasks-file',
    }));
    build.onResolve(
      { filter: /^\.{1,2}\//, namespace: 'month-tasks-file' },
      (args) => {
        const resolved = resolveLocalImport(args.resolveDir, args.path);
        if (resolved === undefined) {
          return { errors: [{ text: `无法解析本地模块：${args.path}` }] };
        }
        return { path: resolved, namespace: 'month-tasks-file' };
      },
    );
    build.onLoad({ filter: /.*/, namespace: 'month-tasks-file' }, (args) => ({
      contents: readFileSync(args.path, 'utf8'),
      loader: path.extname(args.path) === '.json' ? 'json' : 'ts',
      resolveDir: path.dirname(args.path),
    }));
  },
};

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ['month-tasks-entry'],
  bundle: true,
  external: [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    ...builtinModules,
  ],
  format: 'cjs',
  target: 'es2021',
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  plugins: [localModulesPlugin],
  treeShaking: true,
  outfile: path.join(projectRoot, 'main.js'),
  minify: prod,
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
